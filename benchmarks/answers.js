#!/usr/bin/env node
// Readable transcript of a side-by-side run: every prompt, then every arm's
// full answer with its token counts, straight from the raw cells.
//
// Usage: node benchmarks/answers.js <run-dir> [arm ...]   (writes <run-dir>/ANSWERS.md)
//   run-dir: a run-ablation.js output dir (<suite>-s<seed>/<task>__<arm>.json)
//   arms:    order of the columns (default: every arm found, vanilla first)

const fs = require('fs');
const path = require('path');

const dir = process.argv[2];
if (!dir) { console.error('usage: node benchmarks/answers.js <run-dir> [arm ...]'); process.exit(1); }

// Prompts come from run-live.sh, like run-ablation.js reads them.
const live = fs.readFileSync(path.join(__dirname, 'run-live.sh'), 'utf8').replace(/\r\n/g, '\n');
const heredoc = (v) => live.match(new RegExp(`\\n${v}=\\$\\(cat <<'EOF'\\n([\\s\\S]*?)\\nEOF`))[1];
const prompts = {};
for (const line of ['TASKS', 'TASKS_LARGE', 'TASKS_LADDER'].map(heredoc).join('\n').split('\n')) {
  const [task, kind, prompt] = line.split('\t');
  prompts[task] = { kind, prompt };
}

const runs = fs.readdirSync(dir).filter((d) => fs.statSync(path.join(dir, d)).isDirectory()).sort();
const found = new Set();
for (const r of runs) for (const f of fs.readdirSync(path.join(dir, r))) { const m = f.match(/^.+?__(.+)\.json$/); if (m) found.add(m[1]); }
const arms = process.argv.slice(3).length ? process.argv.slice(3) : ['vanilla', ...[...found].filter((a) => a !== 'vanilla').sort()];

// A fence longer than any backtick or tilde run inside the answer.
const fence = (text) => '~'.repeat(Math.max(3, ...(text.match(/~{3,}/g) || []).map((m) => m.length + 1)));

const out = [`# Every prompt and answer: \`${path.basename(dir)}\``, '',
  `Generated by \`node benchmarks/answers.js\` from the raw cells in this directory. Each answer is verbatim; "answer" tokens are billed output minus hidden reasoning. Arms: ${arms.join(', ')}.`, ''];
for (const r of runs) {
  const tasks = [...new Set(fs.readdirSync(path.join(dir, r)).map((f) => f.split('__')[0]).filter((t) => prompts[t]))].sort();
  for (const task of tasks) {
    out.push(`## ${r} / ${task}`, '', `> ${prompts[task].prompt}`, '');
    for (const arm of arms) {
      let j = null;
      try { j = JSON.parse(fs.readFileSync(path.join(dir, r, `${task}__${arm}.json`), 'utf8')); } catch (_) {}
      if (!j || !j.usage) { out.push(`### ${arm}`, '', '_No answer recorded._', ''); continue; }
      const think = (Object.values(j.modelUsage || {})[0] || {}).thinkingTokens || 0;
      const text = (j.result || '').trim();
      const f = fence(text);
      out.push(`### ${arm}: ${j.usage.output_tokens - think} answer tokens, ${j.usage.output_tokens} billed, ${text.split('\n').length} lines`, '', f, text, f, '');
    }
  }
}
fs.writeFileSync(path.join(dir, 'ANSWERS.md'), out.join('\n'));
console.log(`wrote ${path.join(dir, 'ANSWERS.md')}: ${runs.length} runs, arms ${arms.join(', ')}`);
