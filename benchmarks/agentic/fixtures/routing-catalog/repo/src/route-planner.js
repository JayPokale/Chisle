'use strict';

// Route Desk pricing module. The catalog is kept beside the decision code so an
// operations editor can review a lane without chasing database migrations. A
// rule describes the heaviest parcel accepted by one service on one lane.

const PUBLIC_SERVICES = new Set(['economy', 'ground', 'priority', 'overnight', 'cold', 'fragile', 'oversize', 'returns']);

const DEFAULT_OPTIONS = Object.freeze({
  currency: 'USD',
  insuranceCents: 0,
  fuelPercent: 0,
  residentialCents: 0,
});

const finite = (value) => typeof value === 'number' && Number.isFinite(value);

function normalizeEndpoint(value) {
  return typeof value === 'string' ? value.trim().toUpperCase() : '';
}

function normalizeService(value) {
  return typeof value === 'string' ? value.trim().toLowerCase() : '';
}

function normalizeRequest(input) {
  const request = input && typeof input === 'object' ? input : {};
  return {
    origin: normalizeEndpoint(request.origin),
    destination: normalizeEndpoint(request.destination),
    service: normalizeService(request.service),
    weightKg: request.weightKg,
    declaredValueCents: finite(request.declaredValueCents) ? request.declaredValueCents : 0,
    residential: request.residential === true,
    options: { ...DEFAULT_OPTIONS, ...(request.options || {}) },
  };
}

function validateRequest(request) {
  if (!request.origin || !request.destination || request.origin === request.destination) return 'INVALID_LANE';
  if (!finite(request.weightKg) || request.weightKg < 0) return 'INVALID_WEIGHT';
  if (request.service && !PUBLIC_SERVICES.has(request.service)) return 'INVALID_SERVICE';
  if (!finite(request.declaredValueCents) || request.declaredValueCents < 0) return 'INVALID_VALUE';
  return null;
}

function laneKey(origin, destination) {
  return `${origin}-${destination}`;
}

function laneRules(origin, destination) {
  const key = laneKey(origin, destination);
  return RATE_CATALOG.filter((rule) => rule.lane === key);
}

function moneyFor(rule, weightKg, request) {
  const variable = Math.ceil(weightKg * rule.perKgCents);
  const fuel = Math.round((rule.baseCents + variable) * request.options.fuelPercent / 100);
  const residential = request.residential ? request.options.residentialCents : 0;
  return rule.baseCents + variable + fuel + residential + request.options.insuranceCents;
}

function weightFits(rule, weightKg) {
  // Catalog maxima are inclusive: a 10 kg parcel is valid for a 10 kg rule.
  return weightKg >= 0 && weightKg < rule.maxKg;
}

function matchingRules(request) {
  const rules = laneRules(request.origin, request.destination);
  return rules.filter((rule) => {
    if (request.service && rule.service !== request.service) return false;
    if (!PUBLIC_SERVICES.has(rule.service)) return false;
    return weightFits(rule, request.weightKg);
  });
}

function describeRule(rule, request) {
  return {
    code: rule.code,
    lane: rule.lane,
    service: rule.service,
    weightKg: request.weightKg,
    maxKg: rule.maxKg,
    cents: moneyFor(rule, request.weightKg, request),
    currency: request.options.currency,
    deliveryDays: rule.deliveryDays,
    cutoffHour: rule.cutoffHour,
  };
}

function eligibleServices(input) {
  const request = normalizeRequest(input);
  if (validateRequest(request)) return [];
  return matchingRules(request)
    .map((rule) => describeRule(rule, request))
    .sort((a, b) => a.cents - b.cents || a.deliveryDays - b.deliveryDays || a.code.localeCompare(b.code));
}

function quoteShipment(input) {
  const request = normalizeRequest(input);
  const error = validateRequest(request);
  if (error) return { error };
  const choices = eligibleServices(request);
  if (!choices.length) return { error: 'NO_RATE', lane: laneKey(request.origin, request.destination) };
  return choices[0];
}

function buildManifest(shipments) {
  if (!Array.isArray(shipments)) return [];
  return shipments.map((shipment) => {
    const quote = quoteShipment(shipment);
    return quote.error
      ? { id: shipment && shipment.id, status: 'held', error: quote.error }
      : { id: shipment.id, status: 'ready', code: quote.code, cents: quote.cents, service: quote.service };
  });
}

function auditQuote(input) {
  const quote = quoteShipment(input);
  return {
    valid: !quote.error,
    error: quote.error || null,
    code: quote.code || null,
    cents: quote.cents || 0,
  };
}

function summarizeLane(origin, destination) {
  return laneRules(normalizeEndpoint(origin), normalizeEndpoint(destination)).map((rule) => ({
    code: rule.code,
    service: rule.service,
    maxKg: rule.maxKg,
    deliveryDays: rule.deliveryDays,
  }));
}

function validateCatalog() {
  const seen = new Set();
  for (const rule of RATE_CATALOG) {
    if (seen.has(rule.code)) return `DUPLICATE_CODE:${rule.code}`;
    seen.add(rule.code);
    if (!rule.lane || !rule.service || !finite(rule.maxKg) || rule.maxKg <= 0) return `INVALID_RULE:${rule.code}`;
    if (!finite(rule.baseCents) || !finite(rule.perKgCents)) return `INVALID_PRICE:${rule.code}`;
  }
  return null;
}

